def response(part):
    return types.GenerateContentResponse(
        candidates=[
            types.Candidate(content=types.Content(role="model", parts=[part]), finish_reason="STOP")
        ],
        usage_metadata=types.GenerateContentResponseUsageMetadata(
            prompt_token_count=20,
            cached_content_token_count=8,
            candidates_token_count=10,
            thoughts_token_count=5,
            total_token_count=35,
        ),
    )


class GeminiAdapterTests(unittest.TestCase):
    def test_generation_with_five_seconds_left_uses_valid_server_deadline(self):
        config = gemini_config(google_cloud_project="unit-test")
        model = ChatGoogleGenerativeAI(
            model=config.gemini_model, api_key="unit-test", vertexai=False, max_retries=0
        )
        self.addCleanup(model.client.close)
        context = RunContext("test", Budget(timeout=30), ChatRequest("Hello", "chat"))
        agent = create_agent(model, middleware=[ModelBudgetMiddleware(config, Mock())])
        requests = []
        with patch("retail_ai_agent.application.budget.monotonic") as clock:
            clock.return_value = context.budget.started

            def send(client, request, **kwargs):
                requests.append(request)
                if request.url.path.endswith(":countTokens"):
                    clock.return_value = context.budget.started + context.budget.timeout - 5
                    return httpx.Response(200, json={"totalTokens": 20}, request=request)
                payload = response(types.Part(text="Hello")).model_dump(mode="json", by_alias=True)
                return httpx.Response(200, json=payload, request=request)

            with patch.object(httpx.Client, "send", send):
                result = agent.invoke({"messages": [("user", "Hello")]}, context=context)

        self.assertEqual(result["messages"][-1].text, "Hello")
        count, generation = requests
        self.assertTrue(count.url.path.endswith(":countTokens"))
        self.assertTrue(generation.url.path.endswith(":generateContent"))
        self.assertEqual(generation.extensions["timeout"]["read"], 5)
        self.assertEqual(generation.headers["X-Server-Timeout"], "10")

    def test_free_text_pii_is_absent_from_count_generation_and_final_answer(self):
        config = gemini_config(google_cloud_project="unit-test")
        model = ChatGoogleGenerativeAI(
            model=config.gemini_model, api_key="unit-test", vertexai=False, max_retries=0
        )
        self.addCleanup(model.client.close)
        actor = Actor("a", "manager", ("A",))
        analytics = LocalAnalytics(actor)
        self.addCleanup(analytics.connection.close)
        # Independent sources: a user, an unexpected free-text database field, tool
        # arguments generated by Gemini, and fresh PII invented in the final reply.
        email = "private@example.com"
        ip = "192.0.2.25"
        url = "https://example.com/internal"
        card = "4111 1111 1111 1111"
        analytics.connection.execute("UPDATE products SET name = ? WHERE id = 1", (ip,))
        sanitizer = LocalSanitizer(brands=("Calvin Klein",))
        responses = iter(
            [
                response(types.Part(text='{"intent":"ANALYSIS"}')),
                response(
                    types.Part(
                        function_call=types.FunctionCall(
                            name="write_todos",
                            args={"todos": [{"content": url, "status": "in_progress"}]},
                        )
                    )
                ),
                response(
                    types.Part(
                        function_call=types.FunctionCall(
                            name="sql_db_query",
                            args={
                                "query": "SELECT p.name, p.retail_price, u.first_name AS buyer "
                                "FROM order_items i JOIN products p ON i.product_id = p.id "
                                "JOIN users u ON i.user_id = u.id",
                            },
                        ),
                        thought_signature=b"test-signature",
                    )
                ),
                response(
                    types.Part(
                        function_call=types.FunctionCall(
                            name="save_report", args={"body": "Sales: 10"}
                        )
                    )
                ),
                response(types.Part(text=f"Sales: 10. Card {card}")),
                response(types.Part(text='{"intent":"ANALYSIS"}')),
                response(types.Part(text="Done.")),
            ]
        )
        counts, generations = [], []

        def send(client, request, **kwargs):
            body = json.loads(request.content)
            method = request.url.path.rsplit(":", 1)[-1]
            if method == "countTokens":
                counts.append(body)
                return httpx.Response(200, json={"totalTokens": 20}, request=request)
            self.assertEqual(method, "generateContent")
            self.assertLessEqual(request.extensions["timeout"]["read"], 30)
            generations.append(body)
            payload = next(responses).model_dump(mode="json", by_alias=True, exclude_none=True)
            return httpx.Response(200, json=payload, request=request)

        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory)
            reports = ReportService(FileReportStore(path / "reports"), actor)
            trace = JsonlTrace(path / "trace.jsonl")
            graph = create_chat_graph(
                model=model,
                analytics=analytics,
                reports=reports,
                config=config,
                sanitizer=sanitizer,
                trace=trace,
                checkpointer=InMemorySaver(),
                sql=analytics.sql,
            )
            runner = LangGraphRunner(
                graph=graph,
                reports=reports,
                actor=actor,
                config=config,
                trace=trace,
                contexts=RunContextFactory(config, analytics.sql),
                sanitizer=sanitizer,
            )
            chat = ChatService(runner)
            with patch.object(httpx.Client, "send", send):
                question = (
                    "Compare Calvin Klein sales in New York, January 2024, $123.45. "
                    "Customer Alice Morgan, +1 202-555-0148, 42 Cedar Lane. "
                    f"Email: {email}"
                )
                result = chat.ask(ChatRequest(question, "chat", action="report"))
                self.assertEqual(result.status, "complete", result.answer)
                self.assertTrue(result.report_id, result.answer)
                self.assertEqual(len(generations), 5)
                followup = chat.ask(ChatRequest("Thanks", "chat"))
                self.assertEqual(followup.answer, "Done.")
            events = [json.loads(line) for line in trace.path.read_text().splitlines()]
            files = [p.read_text() for p in path.rglob("*") if p.is_file()]
            config_key = runner._graph_config("chat")
            checkpoints = [str(s.values) for s in graph.get_state_history(config_key)]
            metered = [e for e in events if e["event"] == "model_usage"]
            self.assertEqual(len(metered), 7)
            for event in metered:
                self.assertEqual(event["input_tokens"], 20)
                self.assertEqual(event["cached_input_tokens"], 8)
                self.assertEqual(event["output_tokens"], 15)
                self.assertEqual(event["cost_usd"], 0.00004134)
            runs = [e for e in events if e["event"] == "run_finished"]
            self.assertAlmostEqual(runs[0]["model_usd"], 5 * 0.00004134)
            self.assertEqual(runs[0]["unresolved_reserve_usd"], 0)

        self.assertEqual(len(counts), 7)
        self.assertEqual(len(generations), 7)
        for i, (count, generated) in enumerate(zip(counts, generations, strict=True)):
            with self.subTest(call=i):
                for field in ("contents", "tools", "systemInstruction"):
                    self.assertEqual(
                        count["generateContentRequest"].get(field), generated.get(field)
                    )
        for surface in (
            *counts,
            *generations,
            *files,
            *checkpoints,
            result.answer,
            followup.answer,
        ):
            serialized = json.dumps(surface, ensure_ascii=False)
            for raw in (email, ip, url, card, "Private", "Alice", "Morgan", "555-0148", "Cedar"):
                self.assertNotIn(raw, serialized)

        masked_reply = "Sales: 10. Card [REDACTED_CREDIT_CARD]"
        self.assertEqual(result.answer.splitlines()[0], masked_reply)
        # Check both messages loaded back from the conversation checkpoint.
        history = generations[-1]["contents"]
        self.assertIn("[REDACTED_EMAIL]", history[0]["parts"][0]["text"])
        self.assertIn(masked_reply, history[1]["parts"][0]["text"])
        self.assertIn("[REDACTED_EMAIL]", generations[0]["contents"][0]["parts"][0]["text"])
        parts = [p for m in generations[4]["contents"] for p in m["parts"]]
        calls = {p["functionCall"]["name"]: p["functionCall"] for p in parts if "functionCall" in p}
        results = {
            p["functionResponse"]["name"]: p["functionResponse"]["response"]
            for p in parts
            if "functionResponse" in p
        }
        self.assertEqual(calls["write_todos"]["args"]["todos"][0]["content"], "[REDACTED_URL]")
        self.assertEqual(
            results["sql_db_query"]["rows"][0],
            {"name": "[REDACTED_IP]", "retail_price": 10, "buyer": "[REDACTED]"},
        )
        self.assertIn("write_todos", results)
        self.assertIn(
            b64encode(b"test-signature").decode(), [p.get("thoughtSignature") for p in parts]
        )
        declarations = [f for t in generations[1]["tools"] for f in t["functionDeclarations"]]
        self.assertEqual(
            {f["name"] for f in declarations},
            {
                "write_todos",
                "sql_db_query",
                "save_report",
                "list_reports",
                "show_report",
                "delete_reports",
            },
        )
        self.assertNotIn("runtime", str(declarations))
